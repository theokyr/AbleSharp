using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using System.Xml.Linq;
using System.Xml.Serialization;

namespace AbleSharp.Schema.Generation;

/// <summary>
/// Emits strongly-typed Ableton schema classes for a specific schema version.
/// </summary>
public sealed class SchemaCodeEmitter
{
    /// <summary>
    /// Generates C# source for the supplied schema target.
    /// </summary>
    /// <param name="namespaceRoot">Namespace root used by generated types.</param>
    /// <param name="target">Schema generation target metadata.</param>
    /// <param name="schemaContent">Ableton schema XML content.</param>
    /// <returns>Generated C# source code.</returns>
    public string Generate(string namespaceRoot, SchemaGenerationTarget target, string schemaContent)
    {
        if (string.IsNullOrWhiteSpace(namespaceRoot))
        {
            throw new ArgumentException("Namespace root cannot be null or empty.", nameof(namespaceRoot));
        }

        if (target is null)
        {
            throw new ArgumentNullException(nameof(target));
        }

        if (string.IsNullOrWhiteSpace(schemaContent))
        {
            throw new ArgumentException("Schema content cannot be empty.", nameof(schemaContent));
        }

        var document = XDocument.Parse(schemaContent, LoadOptions.PreserveWhitespace);
        var schemaRoot = document.Root ?? throw new InvalidDataException("Schema XML did not contain a root element.");

        var definitions = schemaRoot
            .Elements()
            .GroupBy(e => e.Name.LocalName)
            .ToDictionary(g => SanitizeIdentifier(g.Key), g => g.Last(), StringComparer.Ordinal);

        var writer = new CodeWriter();
        var context = new GenerationContext(namespaceRoot, target, definitions, writer);

        context.WriteHeader();
        context.GeneratePredefinedTypes();

        foreach (var className in definitions.Keys.OrderBy(name => name, StringComparer.Ordinal))
        {
            context.GenerateClass(className);
        }

        context.WriteFooter();
        return writer.ToString();
    }

    private static string SanitizeIdentifier(string candidate)
    {
        if (string.IsNullOrWhiteSpace(candidate))
        {
            return "SchemaType";
        }

        var builder = new StringBuilder(candidate.Length);
        var first = candidate[0];
        if (!IsValidIdentifierStart(first))
        {
            builder.Append('_');
        }

        foreach (var ch in candidate)
        {
            builder.Append(IsValidIdentifierPart(ch) ? ch : '_');
        }

        return builder.ToString();
    }

    private static bool IsValidIdentifierStart(char ch) => char.IsLetter(ch) || ch == '_';

    private static bool IsValidIdentifierPart(char ch) => char.IsLetterOrDigit(ch) || ch == '_';

    private sealed class GenerationContext
    {
        private static readonly Regex GenericPattern = new(@"(?<generic>\w+)<(?<inner>.+)>", RegexOptions.Compiled | RegexOptions.CultureInvariant);

        private static readonly Dictionary<string, string> PrimitiveTypeMap = new(StringComparer.OrdinalIgnoreCase)
        {
            ["Int"] = "int",
            ["RemoteableInt"] = "int",
            ["Int64"] = "long",
            ["RemoteableInt64"] = "long",
            ["Float"] = "float",
            ["RemoteableFloat"] = "float",
            ["TimeableFloat"] = "float",
            ["UserFloat"] = "float",
            ["Double"] = "double",
            ["RemoteableDouble"] = "double",
            ["String"] = "string",
            ["RemoteableString"] = "string",
            ["Bool"] = "bool",
            ["RemoteableBool"] = "bool",
            ["TimeableBool"] = "bool"
        };

        private readonly string _namespaceRoot;
        private readonly SchemaGenerationTarget _target;
        private readonly IDictionary<string, XElement> _definitions;
        private readonly CodeWriter _writer;
        private readonly Dictionary<string, ClassInfo> _classProperties = new(StringComparer.Ordinal);
        private readonly HashSet<string> _generatedClasses = new(StringComparer.Ordinal);
        private readonly HashSet<string> _generationStack = new(StringComparer.Ordinal);

        public GenerationContext(string namespaceRoot, SchemaGenerationTarget target, IDictionary<string, XElement> definitions, CodeWriter writer)
        {
            _namespaceRoot = namespaceRoot;
            _target = target;
            _definitions = definitions;
            _writer = writer;
        }

        public void WriteHeader()
        {
            var targetNamespace = _target.GetNamespace(_namespaceRoot);

            _writer.WriteLine("// <auto-generated />");
            _writer.WriteLine("// Generated by AbleSharp.Schema.Generation.SchemaCodeEmitter");
            _writer.WriteLine("#pragma warning disable CS8618");
            _writer.WriteLine();
            _writer.WriteLine("using System;");
            _writer.WriteLine("using System.Collections.Generic;");
            _writer.WriteLine("using System.Xml.Serialization;");
            _writer.WriteLine();
            _writer.WriteLine($"namespace {targetNamespace};");
            _writer.WriteLine();
            _writer.WriteLine("public static class SchemaMetadata");
            _writer.WriteLine("{");
            _writer.Indent();
            _writer.WriteLine($"public const string VersionId = \"{_target.VersionId}\";");
            _writer.WriteLine($"public const string NamespaceSuffix = \"{_target.NamespaceSuffix}\";");
            _writer.Unindent();
            _writer.WriteLine("}");
            _writer.WriteLine();
        }

        public void WriteFooter()
        {
            _writer.WriteLine("#pragma warning restore CS8618");
        }

        public void GeneratePredefinedTypes()
        {
            if (_generatedClasses.Contains("Slot"))
            {
                return;
            }

            GenerateSimpleClass("Slot", builder =>
            {
                _writer.WriteLine("public class Slot<T>");
                _writer.WriteLine("{");
                _writer.Indent();
                _writer.WriteLine("[XmlElement]");
                _writer.WriteLine("public T Value { get; set; }");
                _writer.Unindent();
                _writer.WriteLine("}");
            });

            GenerateArrayClass("Array8", "byte[]", "8-bit unsigned integers");
            GenerateArrayClass("ArrayU8", "byte[]", "array of bytes");
            GenerateArrayClass("ArrayFloat", "float[]", "array of floats");

            GenerateSimpleClass("RemoteableArray", builder =>
            {
                _writer.WriteLine("public class RemoteableArray<T>");
                _writer.WriteLine("{");
                _writer.Indent();
                _writer.WriteLine("[XmlElement]");
                _writer.WriteLine("public T[] Items { get; set; }");
                _writer.Unindent();
                _writer.WriteLine("}");
            });

            GenerateSimpleClass("Rect", builder =>
            {
                _writer.WriteLine("public class Rect");
                _writer.WriteLine("{");
                _writer.Indent();
                _writer.WriteLine("[XmlElement]");
                _writer.WriteLine("public int X { get; set; }");
                _writer.WriteLine("[XmlElement]");
                _writer.WriteLine("public int Y { get; set; }");
                _writer.WriteLine("[XmlElement]");
                _writer.WriteLine("public int Width { get; set; }");
                _writer.WriteLine("[XmlElement]");
                _writer.WriteLine("public int Height { get; set; }");
                _writer.Unindent();
                _writer.WriteLine("}");
            });

            GeneratePlaceholderClass("PythonListWrapper");
            GeneratePlaceholderClass("ZoneRange");
            GeneratePlaceholderClass("ZoneSettings");
            GeneratePlaceholderClass("BeatGrid");
            GeneratePlaceholderClass("TrackDevice");
            GeneratePlaceholderClass("RemoteablePoint");

            foreach (var simpleType in SimpleStubTypes)
            {
                GeneratePlaceholderClass(simpleType);
            }

            _writer.WriteLine();
        }

        private void GeneratePlaceholderClass(string className)
        {
            if (_generatedClasses.Add(className))
            {
                _writer.WriteLine($"public class {className} {{ }}");
            }
        }

        public void GenerateClass(string className)
        {
            if (string.IsNullOrWhiteSpace(className))
            {
                return;
            }

            className = SanitizeIdentifier(className);

            if (_generatedClasses.Contains(className))
            {
                return;
            }

            if (_generationStack.Contains(className))
            {
                return;
            }

            _generationStack.Add(className);

            if (!_definitions.TryGetValue(className, out var classElement))
            {
                classElement = CreateStubElement(className);
            }

            _generatedClasses.Add(className);

            _writer.WriteLine("/// <summary>");
            _writer.WriteLine($"/// Represents an Ableton {className} element");
            _writer.WriteLine("/// </summary>");
            _writer.WriteLine($"[XmlRoot(\"{classElement.Name.LocalName}\")] ");
            _writer.WriteLine($"public class {className}");
            _writer.WriteLine("{");
            _writer.Indent();

            foreach (var property in classElement.Elements())
            {
                GenerateProperty(className, property);
            }

            _writer.Unindent();
            _writer.WriteLine("}");
            _writer.WriteLine();

            _generationStack.Remove(className);
        }

        private void GenerateProperty(string className, XElement propertyElement)
        {
            var originalName = propertyElement.Name.LocalName;
            var classAttr = propertyElement.Attribute("Class")?.Value;
            var typeAttr = propertyElement.Attribute("Type")?.Value;
            var xmlName = propertyElement.Attribute("InternalName")?.Value ?? originalName;

            var propertyName = GetUniquePropertyName(className, originalName);
            var propertyType = ResolvePropertyType(classAttr, typeAttr);

            _writer.WriteLine("/// <summary>");
            _writer.WriteLine($"/// Gets or sets the {SplitCamelCase(originalName)}");
            _writer.WriteLine("/// </summary>");
            _writer.WriteLine($"[XmlElement(\"{xmlName}\")] ");
            _writer.WriteLine($"public {propertyType} {propertyName} {{ get; set; }}");
            _writer.WriteLine();
        }

        private string ResolvePropertyType(string? classAttr, string? typeAttr)
        {
            if (string.IsNullOrWhiteSpace(classAttr))
            {
                return "string";
            }

            var rawClass = classAttr!.Trim();

            if (GenericPattern.IsMatch(rawClass))
            {
                var genericMatch = GenericPattern.Match(rawClass);
                var genericType = SanitizeIdentifier(genericMatch.Groups["generic"].Value);
                var innerTypeName = genericMatch.Groups["inner"].Value;
                var resolvedInnerType = ResolvePropertyType(innerTypeName, typeAttr);
                return $"{genericType}<{resolvedInnerType}>";
            }

            var sanitizedClass = SanitizeIdentifier(rawClass);

            if (PrimitiveTypeMap.TryGetValue(sanitizedClass, out var primitive))
            {
                return primitive;
            }

            if (sanitizedClass.IndexOf("Array", StringComparison.Ordinal) >= 0 && typeAttr is not null)
            {
                return MapArrayType(sanitizedClass, typeAttr);
            }

            EnsureClassGenerated(sanitizedClass);
            return sanitizedClass;
        }

        private static string MapArrayType(string classType, string typeValue)
        {
            return classType switch
            {
                "Array8" or "ArrayU8" => "byte[]",
                "ArrayFloat" => "float[]",
                "RemoteableArray" => "RemoteableArray<object>",
                _ => "object[]"
            };
        }

        private void EnsureClassGenerated(string className)
        {
            className = SanitizeIdentifier(className);

            if (_generatedClasses.Contains(className))
            {
                return;
            }

            if (!_definitions.ContainsKey(className))
            {
                _definitions[className] = CreateStubElement(className);
            }

            GenerateClass(className);
        }

        private static XElement CreateStubElement(string className)
        {
            return new XElement(className);
        }

        private void GenerateSimpleClass(string className, Action<CodeWriter> generator)
        {
            if (!_generatedClasses.Add(className))
            {
                return;
            }

            generator(_writer);
            _writer.WriteLine();
        }

        private void GenerateArrayClass(string className, string propertyType, string description)
        {
            GenerateSimpleClass(className, builder =>
            {
                _writer.WriteLine("/// <summary>");
                _writer.WriteLine($"/// Represents an {description}");
                _writer.WriteLine("/// </summary>");
                _writer.WriteLine($"public class {className}");
                _writer.WriteLine("{");
                _writer.Indent();
                _writer.WriteLine("[XmlElement]");
                _writer.WriteLine($"public {propertyType} Data {{ get; set; }}");
                _writer.Unindent();
                _writer.WriteLine("}");
            });
        }

        private string GetUniquePropertyName(string className, string originalName)
        {
            className = SanitizeIdentifier(className);
            var classInfo = _classProperties.GetOrAdd(className, static name => new ClassInfo(name));

            var baseName = NormalizePropertyName(originalName);
            var uniqueName = baseName;
            var index = 1;
            while (!classInfo.PropertyNames.Add(uniqueName))
            {
                uniqueName = $"{baseName}{index++}";
            }

            return uniqueName;
        }

        private static string NormalizePropertyName(string value)
        {
            if (string.IsNullOrWhiteSpace(value))
            {
                return "Property";
            }

            if (value.Contains('.'))
            {
                value = Regex.Replace(value, @"\.\d+$", match => match.Value.Replace(".", string.Empty));
                value = string.Join(string.Empty, value.Split('.').Select(SanitizeIdentifier));
            }

            value = SanitizeIdentifier(value);
            if (string.IsNullOrWhiteSpace(value))
            {
                return "Property";
            }

            if (!char.IsLetter(value[0]))
            {
                value = $"_{value}";
            }

            return value + "Property";
        }

        private static string SplitCamelCase(string text)
        {
            if (string.IsNullOrWhiteSpace(text))
            {
                return "value";
            }

            return Regex.Replace(text, "([A-Z])", " $1", RegexOptions.Compiled).Trim();
        }

